const AS_OF = new Date("2026-09-27T12:00:00.000Z");
const SERIES_DAYS = 90;

function pad(value: number): string {
  return String(value).padStart(2, "0");
}

function isoDaysAgo(daysAgo: number): string {
  const date = new Date(AS_OF);
  date.setUTCDate(date.getUTCDate() - daysAgo);
  return `${date.getUTCFullYear()}-${pad(date.getUTCMonth() + 1)}-${pad(date.getUTCDate())}`;
}

function isoDateTimeDaysAgo(daysAgo: number, hour: number): string {
  const date = new Date(AS_OF);
  date.setUTCDate(date.getUTCDate() - daysAgo);
  date.setUTCHours(hour, 12, 0, 0);
  return date.toISOString();
}

function seeded(seed: number): () => number {
  let t = seed >>> 0;
  return () => {
    t += 0x6d2b79f5;
    let r = Math.imul(t ^ (t >>> 15), 1 | t);
    r ^= r + Math.imul(r ^ (r >>> 7), 61 | r);
    return ((r ^ (r >>> 14)) >>> 0) / 4294967296;
  };
}

function buildGrowth(
  seed: number,
  start: { instagram: number; youtube: number; tiktok: number },
  daily: { instagram: number; youtube: number; tiktok: number },
): TimeSeriesData[] {
  const rand = seeded(seed);
  let instagram = start.instagram;
  let youtube = start.youtube;
  let tiktok = start.tiktok;
  const points: TimeSeriesData[] = [];

  for (let i = SERIES_DAYS - 1; i >= 0; i -= 1) {
    instagram += Math.round(daily.instagram * (0.72 + rand() * 0.7));
    youtube += Math.round(daily.youtube * (0.65 + rand() * 0.8));
    tiktok += Math.round(daily.tiktok * (0.8 + rand() * 0.85));
    points.push({
      date: isoDaysAgo(i),
      instagram,
      youtube,
      tiktok,
      total: instagram + youtube + tiktok,
    });
  }

  return points;
}

function demo(
  platform: Platform,
  age: [number, number, number, number, number],
  gender: { female: number; male: number; other: number },
  topCountries: { country: string; percent: number }[],
): PlatformDemographics {
  return {
    platform,
    age: [
      { range: "13-17", percent: age[0] },
      { range: "18-24", percent: age[1] },
      { range: "25-34", percent: age[2] },
      { range: "35-44", percent: age[3] },
      { range: "45+", percent: age[4] },
    ],
    gender,
    topCountries,
  };
}

